import { NotificationBell } from "@dss/ui";
import type { Role } from "@/db/schema/users";
import { acknowledgeNotificationAction, dismissAllNotificationsAction, dismissNotificationAction } from "@/app/actions/notifications";
import { visibleNotificationKeys } from "@/lib/notifications/dismiss-keys";
import { fetchPortalNotifications, withoutAcknowledged, withoutDismissed } from "@/lib/notifications/portal";
import { listInventoryNotifications } from "@/lib/notifications/queries";

/**
 * ============================================================================
 * 머리말의 알림 종 — **이 시스템의 알림 + 다른 시스템들의 알림**
 * ============================================================================
 * 사내 시스템이 여럿인데(A/S · 계측기 · 개선요청 · PO/내자 · 휴가 · 게시판 · 재고)
 * 「어느 시스템에서 종을 열어도 같은 알림을 본다」가 목표다. 그래서 길이 둘이다:
 *
 *   ① 재고 → 포털  (notifications/portal.ts)  POST · Basic client_secret · 남의 알림을 받아 온다
 *   ② 포털 → 재고                              GET  · 포털이 서명한 Bearer · 우리 알림을 내준다
 *                                              (app/api/integration/notifications)
 *
 * ── 🔴 자기 알림은 자기가 붙인다 ────────────────────────────────────────
 * 포털은 **부른 사이트 자신에게는 묻지 않는다.** 그래서 ① 의 답에는 재고의 알림이 들어
 * 있지 않고, 들어 있어서도 안 된다 — 포털은 30초 캐시를 들기 때문에, 자기 알림까지
 * 거기서 받으면 **방금 확인한 신청이 30초 동안 종에 남는다**(사람이 지금 보고 있는 바로
 * 이 화면에서). 그래서 여기서 **우리 DB 의 목록**과 **포털이 준 목록**을 합친다. 둘은
 * 겹치지 않는다.
 *
 * 🔴 **자기 것이 앞, 포털에서 온 것이 뒤**다. 지금 재고 관리를 보고 있는 사람의 할 일이
 *    먼저 보여야 하고, 받은 목록은 다시 섞지 않는다 — 포털이 정한 차례가 있다.
 *
 * ── 🔴 개수는 두 쪽을 **더한다**(다시 세지 않는다) ──────────────────────
 * 묶음은 받은 숫자를 그대로 찍는다(@dss/ui README 7절). 양쪽 count 모두 「그 시스템이
 * 센 진짜 개수」다. `items.length` 로 다시 세면 둘 다 거짓이 된다.
 *
 * ── 🔴 머리말의 「대기 N」 배지를 **대신하지 않는다** ────────────────────
 * 그 배지는 「부품 요청」 메뉴 옆에 그대로 남는다(2026-10-15 에 「기록 내역」에서 옮겨
 * 왔다 — 신청이 보이는 자리가 `/requests` 하나가 됐다). 역할이 다르다: 배지는 **그
 * 화면에 할 일이 있다**는 표시이고, 종은 **여러 시스템의 알림을 모으는 자리**다.
 *
 * ── 🔴 둘 다 던지지 않는다 ──────────────────────────────────────────────
 * DB 가 멎어도(queries.ts 가 삼킨다) 포털이 죽거나 거절해도(portal.ts 가 삼킨다) 빈
 * 목록이 온다. 그래서 한쪽이 없으면 **나머지만** 그려지고, 둘 다 없으면 종이 아예
 * 그려지지 않는다 — 어느 경우에도 화면은 뜬다. 그래서 이 자리에 error boundary 가
 * 필요 없다.
 *
 * ── 🔴 지우기(✕)는 **포털에 적힌다** ───────────────────────────────────
 * 「확인했다」는 그 알림을 만든 시스템에만 적을 수 있지만, 「그만 보겠다」는 포털에
 * 적힌다(2026-10-19). 그래서 어느 시스템에서 지우든 사내 시스템 **전부의 종**에서
 * 사라진다. 적는 자리는 서버 액션이다 — 평범한 함수는 클라이언트 경계를 건너지
 * 못하고, 중계 통로를 뚫으면 위에서 피한 「시크릿을 다루는 자리」가 늘어난다
 * (app/actions/notifications.ts).
 *
 * 🔴 **제 줄은 우리가 걸러야 한다.** 남의 줄은 포털이 걸러서 보내지만(items 에서
 *    빠지고 count 도 줄어 있다), 재고관리의 알림은 포털이 애초에 보내지 않아
 *    손댈 수 없다 — 그것을 거르라고 포털이 `dismissed` 를 함께 보낸다. 안 거르면
 *    **「재고관리에서 지웠는데 재고관리 종에만 그대로 뜬다」**가 된다. 거르는 함수
 *    (withoutDismissed)가 **개수까지 함께 줄인다** — 줄은 빠졌는데 배지 숫자가
 *    그대로면 「눌러도 안 없어지는 숫자」가 된다.
 *
 * 🔵 포털이 보낸 `others.count` 는 **손대지 않는다.** 남의 줄 몫이고 지움이 이미
 *    반영돼 있다. 줄이는 것은 우리가 더한 제 줄 몫뿐이다.
 *
 * ── 🔴 확인(onAcknowledge)도 **넘긴다** (2026-10-22) ────────────────────
 * 2026-10-22 까지 아래 종 자리에는 「**넘기지 않는 이유**」가 적혀 있었다: 이 시스템의
 * 알림은 상태가 바뀌면 저절로 사라지고, 포털에서 온 줄은 **그 알림을 만든 시스템에서만**
 * 확인을 적을 수 있다는 것이었다.
 *
 * 🔴 **뒷말의 전제가 사라졌다.** 포털에 확인을 적는 통로가 생겼다(dss-auth 의
 *    `/api/integration/notification-acknowledgements`, 2026-10-22). 지움과 똑같이 **남의
 *    시스템 줄이어도 여기서 적을 수 있다.**
 *
 * 🔴 **앞말도 사용자 요구 앞에서 깨졌다.** 「상태가 바뀌면 사라진다」가 [재고 부족]에는
 *    맞지 않는다 — 그 줄은 **사건이 아니라 상태**라 부품을 채워 넣기 전까지 계속 서 있다
 *    (bell-items.ts 의 MAX_LOW_STOCK_ITEMS 주석). 사용자가 「[재고부족] 같은 경우는
 *    확인하면 알림이 사라지도록」이라고 콕 집은 줄이 바로 그것이다(2026-10-22).
 *
 * 🔴 **그래서 이 집은 제 줄도 보낸다 — 휴가·게시판과 반대다.** 그 둘은 제 줄을 일부러 안
 *    보냈다(휴가의 제 줄은 결재 대기뿐이고, 게시판은 글을 열면 사라지는 다른 길이 이미
 *    있었다). 여기는 제 줄에 [재고 부족]이 있고 **제 확인 기록 표가 없어** 적을 곳이
 *    포털뿐이다. 포털의 확인 통로는 **전체 목록**을 보고 지문을 계산하므로 제 줄도 그 안에
 *    있다.
 *
 * 🔵 **안전한 까닭 — 판단은 전부 포털이 한다.** 포털은 분류가 「정보 확인용(INFO)」인 줄만
 *    `acknowledged` 에 담는다. 이 시스템의 승인용 줄(확인 대기·결재 차례)은 확인을 적어도
 *    **안 빠진다.** 그래서 이 조각에는 종류를 가리는 갈래가 한 줄도 없다.
 *
 * 🔴 **두 방향이 다 있어야 한다.** ①만 하면 반쪽이다 — 제 줄은 **제 DB 에서 그리므로**
 *    포털에 확인을 적어도 이 집 종에서는 안 사라진다. ②가 아래 `withoutAcknowledged` 다.
 *
 * 🔴 확인이 **실패해도 그 줄이 향하던 화면으로 가는 것을 막지 않는다.** 이동은 평범한
 *    `<a href>` 가 하고, @dss/ui 가 이 함수를 try 로 감싼다(BellBehavior 의
 *    notifyAcknowledged). 서버 액션 쪽도 제 손으로 한 번 더 삼킨다.
 *
 * ── 🔴 「보이는 알림 지우기」(onDismissAll)도 **넘긴다** (2026-10-20) ────
 * 줄이 여럿이면 ✕ 를 여러 번 눌러야 했다. 그 단추는 A/S 에만 있었는데, 이제 @dss/ui 가
 * **단추도 글자도 개수도** 그린다 — 사이트가 하는 일은 함수를 넘기는 것뿐이다(그쪽
 * README 「보이는 알림 지우기」 절).
 *
 * 🔴 그 자리는 `() => void` 로 **인자를 안 받는데** 지울 열쇠 목록을 아는 것은 이쪽이다.
 *    그래서 **값을 미리 묶어** 넘긴다(`…bind(null, 열쇠들)`). 묶은 것도 여전히 서버
 *    액션이라 경계를 건넌다 — 평범한 화살표 함수는 못 건넌다(이 조각에 "use client" 가
 *    없는 것이 그 짝이다).
 *
 * 🔴 묶는 목록은 **합친 뒤의 `items`** 다 — 제 줄과 포털 줄 **둘 다**. 계측기·PO 는 남의
 *    알림만 그려서 포털 목록이 곧 전부였지만, 여기는 제 알림을 제 손으로 이어 붙인다.
 *    포털에서 온 줄만 묶으면 **「전부 지우기를 눌렀는데 내 알림만 남는다」**가 된다.
 *
 * 두 물음은 **나란히** 나간다 — 우리 DB 가 포털을 기다릴 이유가 없다.
 * ============================================================================
 */
export async function HeaderNotificationBell({ userId, role, subject }: { userId: string; role: Role; subject: string }) {
  // 🔴 `subject` 는 **포털 번호**(`session.user.authSub`)다. 포털에 남의 알림을 물을 때 쓰던
  //    그 값을 우리 질의에도 그대로 넘긴다 — 「지금 내 차례인 불출 결재」가 그 번호로만 갈린다
  //    (notifications/queries.ts 의 `NotificationViewer.sub`). **users 를 다시 읽지 않는다.**
  const [raw, others] = await Promise.all([listInventoryNotifications({ id: userId, role, sub: subject }), fetchPortalNotifications(subject)]);

  // 🔴 이 한 줄이 없으면 「여기서 지웠는데 여기서만 그대로 뜬다」가 된다(위 머리말).
  const notDismissed = withoutDismissed(raw, others.dismissed);

  // 🔴 **확인(✓)은 지움(✕)과 따로 거른다** (2026-10-22, 위 머리말의 「확인」 절).
  //    두 열쇠 목록을 한 배열로 이어 붙여 한 번에 거르면 코드가 한 줄 짧아지는 대신 **수명이
  //    정반대인 두 뜻이 섞인다** — 지움은 다시 로그인하면 돌아오고 확인은 안 돌아온다.
  //    섞어 두면 확인을 지움으로 읽어 안 돌아와야 할 줄이 돌아오거나, 지움을 확인으로 읽어
  //    영영 사라진다. 그래서 **차례로 두 번** 거른다.
  const mine = withoutAcknowledged(notDismissed, others.acknowledged);

  const items = [...mine.items, ...others.items];

  // 🔴 **알림이 0건이면 머리말이 예전과 글자 하나 다르지 않아야 한다.** 묶음도 빈
  //    목록이면 스스로 아무것도 그리지 않지만(그쪽 시험), 여기서 한 겹 더 막아 둔다.
  if (items.length === 0) return null;

  // ── 🔴 일괄 지우기에 넘길 열쇠 — **지금 그리는 줄 전부** ────────────────
  // 🔴 **합친 뒤의 목록**을 본다(제 줄 + 포털 줄). 어느 한쪽만 묶으면 단추에 적힌 수와
  //    실제로 지워지는 줄이 어긋난다 — 제 줄을 빠뜨리면 「전부 지우기를 눌렀는데 내
  //    알림만 남는다」가 된다.
  // 🔴 `visibleNotificationKeys` 가 **그릴 수 없는 주소의 줄을 뺀다.** 종도 그 줄을 안
  //    그리고 단추에 적는 수도 그렇게 남은 줄 수라, 여기서 빼지 않으면 「3건」을 눌렀는데
  //    4건이 지워진다(그 함수 주석).
  // 🔴 묶는 일은 **그릴 때마다** 한다 — 이 조각이 그려지는 순간의 목록이 곧 사람이 보는
  //    목록이다.
  const dismissAll = dismissAllNotificationsAction.bind(null, visibleNotificationKeys(items));

  return (
    <NotificationBell
      items={items}
      // 🔴 두 쪽을 **더한다**(위 머리말). items.length 가 아니다.
      count={mine.count + others.count}
      label="알림"
      // 🔴 줄을 **누르면** 「확인했다」가 포털에 적힌다(2026-10-22, 위 머리말의 확인 절).
      //    2026-10-22 까지 여기에는 「넘기지 않는 이유」가 적혀 있었고 그 전제가 사라졌다.
      //    🔴 ✕(onDismiss)와 **다른 일**이다 — 합치지 말 것. 수명이 정반대다.
      //    🔵 제 줄이든 포털 줄이든 가리지 않고 보낸다. 무엇이 실제로 사라질지는 포털이
      //       정하고(정보 확인용 줄만), 승인용 줄은 확인을 적어도 종에 남는다.
      onAcknowledge={acknowledgeNotificationAction}
      // colorScheme 은 넘기지 않는다. 이 사이트는 밝은 화면뿐이라 기본값 "host"
      // (조상에 .dark 가 있을 때만 어두워진다)가 그대로 옳다(@dss/ui README 4절).
      //
      // 🔴 `onDismiss` 를 **넘겼을 때만** 줄마다 ✕ 가 그려진다(@dss/ui). 넘기는 것은
      //    서버 액션이라 번들에는 이름표만 나가고 `client_secret` 은 서버에 남는다 —
      //    이 조각에 "use client" 가 없는 것이 그 판단의 짝이다.
      onDismiss={dismissNotificationAction}
      // 🔴 「보이는 알림 지우기 n건」 — 이 함수를 **넘긴 사이트에만** 단추가 그려지고,
      //    그릴 줄이 있을 때만 선다(@dss/ui). 적히는 수는 묶음이 세는 **지금 그리는 줄
      //    수**이고, 위에서 묶은 열쇠도 같은 기준으로 걸러 둬 둘이 어긋나지 않는다.
      onDismissAll={dismissAll}
      // 🔴 `canDismiss` 는 넘기지 않는다 = **모든 줄에 ✕ 가 선다.** 제 줄도 지울 수
      //    있다. 한때 A/S 가 「처리해야 사라지는 제 할 일」은 못 지우게 가렸는데,
      //    2026-10-20 에 그 규칙을 **풀었다**(A/S 의 551641f) — 다른 시스템의 종에서는
      //    어차피 지워지므로, 막는 것이 아니라 헷갈리게 만들고 있었기 때문이다.
      //    같은 까닭이 여기에도 그대로 적용된다.
    />
  );
}
