/**
 * 🔴 **이름이 안 적힌 대리 결재**에 쓰는 글자. 표가 번호·이름 두 칸을 다 널 허용이라 생길 수
 * 있는 모양이고, 그때 「(null 대리)」를 그리느니 **아는 것만** 말한다.
 */
export const APPROVAL_DELEGATE_UNNAMED = "(대리 결재)";

/**
 * 결재자 이름 **뒤에 덧붙일 한 토막**. 덧붙일 것이 없으면 `null`.
 *
 * 🔴 **대리로 눌린 자리에만 글자가 있다.** 나머지 셋은 전부 `null` 이고, 그 까닭이 갈래마다 다르다:
 *  · `SELF` — 적힌 사람이 눌렀다. 덧붙일 말이 없다(지금까지와 한 글자도 다르지 않다).
 *  · `UNDECIDED` — 아직 아무도 안 눌렀다. 「누가 눌렀나」를 말할 수 없다.
 *  · `UNRECORDED` — 🔴 **옛 줄이다. 그래도 지금까지처럼 이름 하나만 그린다**(2026-10-22 결정).
 *    「모른다」를 화면에 적으면 **2026-10-21 이전의 결재가 전부 수상해 보인다.** 그런데 그때는
 *    위임 기능 자체가 없어서 **적힌 사람이 누른 것이 사실상 맞다.** 다만 「사실상 맞다」와
 *    「적혀 있다」는 다른 말이라, **가르는 일은 코드가 계속한다**(`approvalStepActor` 의
 *    `UNRECORDED` 갈래) — 화면에서만 `SELF` 와 같게 보일 뿐이다. 🔴 그래서 이 갈래를 위 `SELF`
 *    와 **한 값으로 합치지 마라.** 합치는 순간 옛 줄이 「본인이 눌렀다」가 되어 과거를 지어낸다.
 *
 * 🔵 **괄호를 씌우는 까닭**은 바로 앞의 결재자 이름에 **매달린 말**로 읽히게 하려는 것이다:
 *    괄호가 없으면 「이○○ 대리」가 직급(대리)으로 읽힐 자리가 생긴다.
 */
export function approvalDelegateSuffix(actor: ApprovalStepActor): string | null {
  if (actor.kind !== "DELEGATED") return null;
  return actor.delegateName === null ? APPROVAL_DELEGATE_UNNAMED : `(${actor.delegateName} 대리)`;
}

/**
 * **그 결재를 누구 이름으로 말할 것인가** — 「김○○」 또는 「김○○ (이○○ 대리)」.
 *
 * ── 🔴 **원래 결재권자가 주(主), 대리인이 종(從)이다** ───────────────────
 * 앞에 서는 이름은 **결재선에 적힌 사람**(`approverName`)이다. 대리인이 눌렀어도 그 건의 결재권은
 * 여전히 그 사람의 것이고(`./delegation.ts` 머리말: 위임은 **넘기는 것이 아니라 늘리는 것**),
 * 되짚는 사람이 찾는 것도 「누구 자리였나」다. 실제로 누른 사람은 **그 이름에 매달아** 말한다.
 *
 * 🔴 **두 자리가 이 함수를 함께 쓴다**(반려 사유 상자 · 알림 종). 돌려주는 것이 **한 덩이 글자**인
 * 까닭이 그것이다 — 「이름」과 「꼬리」를 따로 내주면 한쪽은 붙여 쓰고 다른 쪽은 빠뜨리는 날이
 * 오고, 그날 같은 반려가 또 두 얼굴이 된다. 🔵 그래서 부르는 쪽은 **이름 하나가 들어가던 자리에
 * 이 값을 그대로** 넣으면 되고, 모양을 새로 배우지 않는다.
 *
 * 🔵 결재선 그림만 모양이 다르다 — 거기는 상자가 좁아 **두 줄**로 세우고(윗줄 이름, 아랫줄 작고
 *    흐린 꼬리), 그래서 꼬리만 따로 받는다(`approvalDelegateSuffix`). **글자는 같다.**
 */
export function approvalDecidedByName(approverName: string, actor: ApprovalStepActor): string {
  const suffix = approvalDelegateSuffix(actor);
  return suffix === null ? approverName : `${approverName} ${suffix}`;
}
