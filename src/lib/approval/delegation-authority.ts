import type { Role } from "@/db/schema/users";
import { roleAtLeast } from "@/lib/auth/role";

/**
 * ============================================================================
 * 결재권 위임 — 「남의 것까지 되는가」를 가르는 자 하나 (2026-10-26)
 * ============================================================================
 * 2026-10-21 에는 **본인만** 자기 결재권을 맡길 수 있었다. 자리를 갑자기 비우게 된 사람
 * (병가·사고)은 본인이 설정할 수 없어서 **관리자가 남의 결재권도** 맡길 수 있게 넓혔다
 * (사용자 결정. 같은 날 A/S 도 같은 방식으로 바뀌었다). 그때부터 규칙은 한 줄이다:
 *
 *   🔴 **본인 것이면 누구나, 남의 것이면 `ADMIN`.**
 *
 * ── 🔴 왜 파일을 따로 두는가 ───────────────────────────────────────────
 * 이 판정을 묻는 자리가 **셋**이다: 만들기 · 되돌리기(`./delegation-mutations.ts`)와 **모두의
 * 목록**(`./delegation-queries.ts`). 셋이 각자 `roleAtLeast(…, "ADMIN")` 을 적으면, 한 곳만
 * 고치는 날 「보이는데 눌러도 거절당하는 단추」나 그 반대가 생긴다 — 둘 다 오류를 내지 않는다.
 * 🔴 **읽기를 쓰기보다 느슨하게 열지 않는다**: 되돌릴 수 없는 사람에게 남의 위임 목록을 보여
 * 줄 까닭이 없다. 그래서 세 자리가 **같은 자**를 쓴다.
 *
 * 🔵 쓰기 쪽(mutations)에 두지 않고 여기 둔 까닭: 거기 두면 **읽기가 쓰기를 가져오게** 되고,
 *    그 방향은 이 저장소가 어디서도 쓰지 않는다(`./queries.ts` 와 `./mutations.ts` 가 서로를
 *    모르는 것과 같은 짝).
 *
 * ── 🔴 권한 영역(`hasPermission`)이 아니라 **역할 사다리**다 ────────────
 * A/S 는 권한 영역으로 가르지만 **이 저장소에는 그 체계가 없다.** 새로 만들지 않기로 했다 —
 * 역할 셋(VIEWER·STAFF·ADMIN)이 전부이고, 새 체계를 들이면 그 하나만을 위해 설정 화면·표·
 * 기본 정책이 따라붙는다.
 *
 * ── 🔴 이것은 **문이 아니다** ──────────────────────────────────────────
 * 서버 액션은 지금도 `requireSession` 이다(`src/app/actions/approval-delegations.ts` 머리말).
 * 역할로 문을 막으면 **본인 위임까지 막혀** 넓히려던 것이 좁혀진다 — 결재자는 역할과 무관하게
 * 누구나 될 수 있고, 보기 권한자가 결재선에 든 경우가 실제로 있다.
 * ============================================================================
 */

/**
 * 🔴 남의 결재권까지 다룰 수 있는 역할. 🔵 상수로 두는 까닭은 글자를 세 곳에 흩지 않으려는
 * 것이고, 시험이 「무엇이 기준인가」를 이 이름으로 묻을 수 있게 하려는 것이다.
 */
export const DELEGATION_MANAGE_ROLE: Role = "ADMIN";

/**
 * 🔴 「**남의** 결재권까지 맡기거나 거두거나 들여다볼 수 있나」.
 *
 * 🔵 **본인 것은 이 값과 무관하게 언제나 된다.** 부르는 쪽들이 「본인인가」를 먼저 보고, 아닐
 *    때에만 이 답을 쓴다 — 그 차례가 뒤집히면 보기 권한자가 **자기 위임조차** 못 만든다.
 */
export function mayManageOthersDelegations(role: Role): boolean {
  return roleAtLeast(role, DELEGATION_MANAGE_ROLE);
}
