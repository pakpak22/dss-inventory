import type { Role } from "@/db/schema/users";
import { roleAtLeast } from "@/lib/auth/role";

/**
 * ============================================================================
 * 결재권 위임 — 「남의 것까지 되는가」를 가르는 자 하나 (2026-10-26)
 * ============================================================================
 * 2026-10-21 에는 **본인만** 자기 결재권을 맡길 수 있었다. 자리를 갑자기 비우게 된 사람
 * (병가·사고)은 본인이 설정할 수 없어서 **관리자가 남의 결재권도** 맡길 수 있게 넓혔다
 * (사용자 결정. 같은 날 A/S 도 같은 방식으로 바뀌었다). 그때부터 규칙은 한 줄이다:
 *
 *   🔴 **본인 것이면 누구나, 남의 것이면 `ADMIN`.**
 *
 * ── 🔴 왜 파일을 따로 두는가 ───────────────────────────────────────────
 * 이 판정을 묻는 자리가 **셋**이다: 만들기 · 되돌리기(`./delegation-mutations.ts`)와 **모두의
 * 목록**(`./delegation-queries.ts`). 셋이 각자 `roleAtLeast(…, "ADMIN")` 을 적으면, 한 곳만
 * 고치는 날 「보이는데 눌러도 거절당하는 단추」나 그 반대가 생긴다 — 둘 다 오류를 내지 않는다.
 * 🔴 **읽기를 쓰기보다 느슨하게 열지 않는다**: 되돌릴 수 없는 사람에게 남의 위임 목록을 보여
 * 줄 까닭이 없다. 그래서 세 자리가 **같은 자**를 쓴다.
 *
 * ── 🔴 2026-11-17: **맡기는 자리 하나만** 한 겹 좁아졌다 ─────────────────
 * 🔴 **세 자리가 같은 자를 쓴다는 위 문장이 이날 반만 참이 됐다.** 역할 위임이 서면서
 * (설계 B-10 — `./delegated-role.ts`) **임시 `ADMIN`** 이라는 사람이 생겼고, 그 사람에게만
 * 「남의 결재권을 **맡기는**」 길을 닫았다(사용자 결정). 그 하나가 아래
 * `mayCreateOthersDelegation` 이고, 까닭은 그 자리에 적었다.
 * 🔵 **되돌리기와 모두의 목록은 안 좁혔다** — 둘 다 임시 관리자의 임기를 **늘릴 수 없는**
 *    일이라서다(거두기는 권한을 좁히기만 하고, 목록은 읽기다). 그 둘의 까닭도 저마다
 *    `./delegation-mutations.ts` 의 `revokeApprovalDelegation` 머리말과 아래에 적었다.
 * 🔴 그래서 지금 규칙은 **한 줄이 아니라 두 줄**이다. 고칠 때 둘을 함께 읽어라.
 *
 * 🔵 쓰기 쪽(mutations)에 두지 않고 여기 둔 까닭: 거기 두면 **읽기가 쓰기를 가져오게** 되고,
 *    그 방향은 이 저장소가 어디서도 쓰지 않는다(`./queries.ts` 와 `./mutations.ts` 가 서로를
 *    모르는 것과 같은 짝).
 *
 * ── 🔴 권한 영역(`hasPermission`)이 아니라 **역할 사다리**다 ────────────
 * A/S 는 권한 영역으로 가르지만 **이 저장소에는 그 체계가 없다.** 새로 만들지 않기로 했다 —
 * 역할 셋(VIEWER·STAFF·ADMIN)이 전부이고, 새 체계를 들이면 그 하나만을 위해 설정 화면·표·
 * 기본 정책이 따라붙는다.
 *
 * ── 🔴 이것은 **문이 아니다** ──────────────────────────────────────────
 * 서버 액션은 지금도 `requireSession` 이다(`src/app/actions/approval-delegations.ts` 머리말).
 * 역할로 문을 막으면 **본인 위임까지 막혀** 넓히려던 것이 좁혀진다 — 결재자는 역할과 무관하게
 * 누구나 될 수 있고, 보기 권한자가 결재선에 든 경우가 실제로 있다.
 * ============================================================================
 */

/**
 * 🔴 남의 결재권까지 다룰 수 있는 역할. 🔵 상수로 두는 까닭은 글자를 세 곳에 흩지 않으려는
 * 것이고, 시험이 「무엇이 기준인가」를 이 이름으로 묻을 수 있게 하려는 것이다.
 */
export const DELEGATION_MANAGE_ROLE: Role = "ADMIN";

/**
 * 🔴 「**남의** 결재권까지 맡기거나 거두거나 들여다볼 수 있나」.
 *
 * 🔵 **본인 것은 이 값과 무관하게 언제나 된다.** 부르는 쪽들이 「본인인가」를 먼저 보고, 아닐
 *    때에만 이 답을 쓴다 — 그 차례가 뒤집히면 보기 권한자가 **자기 위임조차** 못 만든다.
 */
export function mayManageOthersDelegations(role: Role): boolean {
  return roleAtLeast(role, DELEGATION_MANAGE_ROLE);
}

/**
 * 🔴 「**남의** 결재권을 **맡길** 수 있나」 — 위 자에서 **임시 관리자만** 뺀 것 (2026-11-17).
 *
 * ── 🔴 무엇을 막는가 ──────────────────────────────────────────────────
 * 2026-11-17 에 결재권 위임이 **역할까지 넘기게** 됐다(설계 B-10 — `./delegated-role.ts`).
 * `ADMIN` 이 맡긴 위임의 대리인은 기간 동안 `ADMIN` 이고, 그래서 위 자가 그 사람에게도 **참**이
 * 된다. 그대로 두면 임시 관리자는 「아무 진짜 `ADMIN` → 나」 위임을 **기간을 길게 새로 만들어**
 * 제 임기를 스스로 늘릴 수 있다:
 *  · 자기를 대리인으로 세우는 것은 **일부러 안 막혀 있고**(2026-10-26 결정 — 막는 자리 대신
 *    `created_by_sub` 에 줄마다 남는 기록을 두기로 했다),
 *  · 위임 **기간에 상한이 없다**(`./delegation-input.ts` — 거꾸로인 기간만 막는다).
 * 🔴 그러면 설계 D-7 ③ 의 「역할을 바꾸는 기능은 `ADMIN` 에게도 없다」가 **이 기능 하나로
 * 무효가 된다.** 그래서 임시 관리자에게서 이 길만 닫는다.
 *
 * ── 🔵 **자기 결재권을 맡기는 길은 그대로 열려 있다** ────────────────────
 * 부르는 쪽이 「본인인가」를 **먼저** 보고, 아닐 때에만 이 답을 쓴다(위 자와 같은 약속). 본인
 * 위임은 누구나 하는 일이고(보기 권한자도 한다), 막으면 임시 관리자는 **제 출장조차 남에게 못
 * 맡긴다** — 임기를 늘리는 일과는 아무 상관이 없다.
 *
 * ── 🔵 왜 **진짜 `ADMIN` 인지**를 여기서 다시 묻는가 ─────────────────────
 * 지금 부르는 자리(`./delegation-mutations.ts`)는 위 자를 이미 한 번 물은 **뒤**라 `!delegatedAdmin`
 * 만 봐도 답이 같다. 그래도 둘을 다 묻는 까닭은, **이 자 하나만 물어도 옳은 답이 나와야** 다음
 * 사람이 여기만 보고 새 자리를 걸 수 있기 때문이다. 반쪽짜리 자는 그 자리에서 조용히 열린다.
 *
 * @param role 이번 요청에서 쓰이는 역할(승격됐으면 승격된 값 — 세션의 `user.role`).
 * @param delegatedAdmin 🔴 그 `ADMIN` 이 **위임에서 왔는가**(세션의 `delegatedAdmin`).
 *   **기본값을 두지 마라** — 빠뜨린 자리에서만 울타리가 조용히 풀리고 아무 표시도 안 남는다
 *   (`./delegated-role.ts` 의 `mayChangeApprovalRoute` 와 같은 까닭).
 */
export function mayCreateOthersDelegation(role: Role, delegatedAdmin: boolean): boolean {
  return mayManageOthersDelegations(role) && !delegatedAdmin;
}

