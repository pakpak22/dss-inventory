/* ② 그 신청에 살아 있는 결재건이 있는가 — 있다면 어느 자리인가           */
/* ------------------------------------------------------------------ */

/**
 * [확인] 자리가 잠긴 까닭. 잠기지 않았으면 `null` 을 쓴다(아래 함수).
 *  · `AWAITING_APPROVAL`  — 결재 중인 결재건이 있다.
 *  · `AWAITING_EXECUTION` — 결재가 끝나 **실행을 기다리는** 결재건이 있다.
 *
 * 🔴 둘을 **다른 말로** 보여 준다. 사람이 다음에 해야 할 일이 다르기 때문이다 — 앞은 결재자를
 * 기다리는 것이고, 뒤는 **담당자 자신이 `/approvals` 에서 [실행]을 누르면 되는 것**이다.
 */
export type PartIssueLock = "AWAITING_APPROVAL" | "AWAITING_EXECUTION";

/**
 * 한 반출 신청에 달린 **살아 있는** 결재건의 상태들 → 그 신청의 [확인] 잠금. **순수 함수**다.
 *
 * 🔴 결재 중이 하나라도 있으면 「승인 대기」가 이긴다 — 실행 대기 건을 실행해도 결재 중인 건이
 * 남아 있으면 여전히 다시 올릴 수 없기 때문이다.
 *
 * 🔵 **목록으로 받는 까닭**: 표의 부분 유니크 색인(`stock_issue_approvals_request_open_uq`)이
 *    살아 있는 결재건을 하나로 묶어 두므로 오늘 들어오는 것은 0개 아니면 1개다. 그래도 「하나」로
 *    받게 적어 두면 둘째가 생기는 날 **조용히 문이 열린다** — 세어서 「있으면 잠근다」로 적는
 *    편이 그 사고를 못 내게 한다. A/S 의 같은 함수(`partRequestIssueLockFor`)와 모양을 맞춰
 *    두어 두 저장소를 견주는 사람이 같은 자리를 찾을 수 있게 한다.
 *
 * 🔴 **절차(판)가 켜져 있는지는 보지 않는다.** 관리자가 절차를 꺼도 이미 올라간 결재건은 살아
 * 있어 결재·실행될 수 있고, 그 사이 [확인]으로 한 번 더 내보내면 **같은 부품이 두 번 나간다.**
 */
export function partIssueLockFor(statuses: readonly PartIssueStatus[]): PartIssueLock | null {
  if (statuses.some((status) => status === "PENDING_APPROVAL")) return "AWAITING_APPROVAL";
  if (statuses.some((status) => status === "APPROVED")) return "AWAITING_EXECUTION";
  return null;
}

/**
 * 🔴 잠금이 보는 묶음은 **살아 있는 결재건의 묶음**(`OPEN_PART_ISSUE_STATUSES`)과 **같아야
 * 한다.** 조회가 그 묶음으로 좁혀 읽는데 여기서 다른 상태를 세면, 조회에 걸려 온 줄을 보고도
 * 「잠글 것 없음」이라 답해 문이 열린다. 시험이 둘을 맞춰 본다.
 */
export function isPartIssueLockStatus(status: PartIssueStatus): boolean {
  return isOpenPartIssueStatus(status);
}

