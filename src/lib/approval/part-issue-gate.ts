/**
 * 「부품 불출」 판이 **지금 쓰이고 있는가** — 판이 있고 단계가 1개 이상이다.
 *
 * 🔴 **판이 없거나 단계가 0개면 거짓이고, 그때 이 기능은 없는 것과 같다.** 이것이
 * `./part-issue.ts` 가 `NO_ROUTE` 로 못 박은 안전장치의 화면 쪽 짝이다 — 관리자가 절차를
 * 만들기 전까지 재고가 통째로 잠기면 안 된다.
 *
 * 🔴 **판의 모양을 가리지 않는다**(`steps` 만 본다). 판을 읽는 조회가 둘이고(포털 번호가 든
 * `getCurrentApprovalRouteWithSubs` · 화면용 `getCurrentApprovalRoute`) 돌려주는 타입이 서로
 * 다른데, 이 판정에 필요한 것은 양쪽에 똑같이 있는 단계 목록뿐이다. 타입 하나에 묶으면 부르는
 * 쪽이 맞추려고 값을 옮겨 담게 되고, 그 옮겨 담기가 곧 두 벌이다.
 * 🔵 타입 좁힘까지 겸한다 — 참이면 부르는 쪽이 그 판을 그대로 쓸 수 있다.
 */
export function isPartIssueApprovalRouteInForce<TRoute extends { steps: readonly unknown[] }>(route: TRoute | null): route is TRoute {
  return route !== null && route.steps.length > 0;
}

