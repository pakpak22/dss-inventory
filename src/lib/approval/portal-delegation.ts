/**
 * ============================================================================
 * 포털에 맡긴 결재권 위임 — 이 집이 받아 드는 **그릇** (순수)
 * ============================================================================
 * 2026-11-13 결정으로 결재권 위임을 **포털(dss-auth) 한 곳에 모으기로** 했다
 * (설계: `dss-approvals/DELEGATION_DESIGN.md` 의 B-1·B-2). 지정과 되돌리기는 통합 승인함이
 * 하고, 저장은 포털이 하고, **읽는 것은 각 시스템**이다. 이 파일은 재고관리가 그 답을 들고
 * 다니는 그릇이고 망도 DB 도 여기서 만지지 않는다 — 묻는 일은 `./portal-acting-subs.ts`,
 * 합치는 일은 `./delegation.ts` 의 `actingApproverSubs` 다.
 *
 * `server-only` 를 물지 않는 까닭은 `./delegation.ts`·`./route.ts` 와 같다 — 순수 규칙이라
 * 화면 묶음이 끌어와도 빌드가 깨지지 않아야 하고, 시험이 **그대로 불러** 재 볼 수 있어야 한다.
 *
 * ── 🔴 왜 그릇이 따로 있나. 빈 목록과 「못 물었다」가 다르기 때문이다 ──────
 * 포털에 못 물었을 때 이 시스템은 **「위임 없음」으로 보고 결재를 그대로 진행한다**
 * (설계 B-6). 포털 한 곳이 멈추면 A/S·재고관리·휴가의 결재가 **전부** 멈추는 쪽이 더
 * 비싸다고 판단한 것이다. 🔴 **그 대가는 「대리인만 조용히 막힌다」**이고, 이 저장소들에서
 * 가장 비싼 결함 모양이 바로 그것이다. 그래서 설계 B-7 이 **눈에 보이는 안내를 띄우라**고
 * 못 박았다.
 *
 * 안내를 띄우려면 **「물어봤더니 없더라」와 「못 물었다」가 값에서 갈려 있어야** 한다. 둘 다
 * `[]` 로 뭉개면 안내할 자리에서 구별할 길이 영영 없어진다. 그래서 칸이 둘이다.
 *
 * ── 🔵 이 집에는 **열쇠 변환이 없다** ───────────────────────────────────
 * A/S 는 포털 번호를 `users.sso_subject` 에 따로 들고 있어 묻기 전·받은 뒤 두 번 바꿔야
 * 하지만(설계 C-3), 이 시스템은 **`users.auth_sub` 가 곧 포털 `sub`** 이고 결재 판정의 열쇠도
 * 그 번호다(`./delegation.ts` 머리말). 그래서 포털이 준 값을 **그대로** 쓴다 — 바꾸다 틀릴
 * 자리 자체가 없다.
 *
 * 🔵 **그렇다고 「몇 건을 받았나」를 안 세는 것은 아니다.** 세는 자리를 로그가 아니라 **값**에
 * 두었다: `delegatorSubs.length` 가 곧 그 수이고, 설정 화면이 그것을 사람에게 보인다
 * (`./delegation-screen-data.ts` 의 `portalActing`). 🔴 로그로 세지 않는 까닭은 이 물음이
 * **머리말의 알림 종에서도** 불려 모든 화면마다 한 번씩 돌기 때문이다 — 찍으면 평소에 아무도
 * 안 읽는 줄이 쌓이기만 한다. 로그에 남기는 것은 **이상한 일**뿐이다(그쪽 파일).
 *
 * ── 🔴 재고관리 **자신의 위임을 대신하지 않는다. 둘 다 산다** ────────────
 * 설계 B-4 로 **포털 위임과 각 시스템 위임을 둘 다 살려 두기로** 했다. 그래서 이 값은
 * `approval_delegations`(이 시스템 제 표)를 읽은 결과에 **더해지는** 목록이고, 합치는 자리는
 * `./delegation.ts` 의 `actingApproverSubs` **하나**다 — 「누를 수 있나」가 두 벌로 적히지
 * 않게 하려는 그 함수의 원칙 그대로다.
 * ============================================================================
 */

/**
 * 포털에 물어본 결과. 🔴 **두 칸을 한 칸으로 줄이지 마라**(파일 머리말).
 */
export type PortalDelegations = {
  /**
   * 포털이 「이 사람이 지금 대신할 수 있다」고 답한 결재권자들의 **포털 번호**.
   *
   * 🔵 **본인이 섞여 있어도 된다** — 포털은 답의 맨 앞에 부른 사람 자신을 넣어 준다(설계
   * C-2). 합치는 함수가 본인을 맨 앞에 두고 중복을 걷으므로 여기서 빼지 않는다.
   *
   * 🔵 **이 시스템에 계정이 없는 사람의 번호가 섞여 있을 수 있다.** 포털은 사내 전체의
   * 명부이고 재고관리는 「지정된 사람만」 들어오기 때문이다 — 해롭지 않다. 그 번호는
   * 결재선 단계의 `approver_sub` 와 영영 맞지 않아 `inArray` 에서 그냥 빠진다.
   */
  delegatorSubs: readonly string[];
  /**
   * 🔴 **포털에 못 물었다**(죽었거나 · 느렸거나 · 우리를 거절했거나 · 모르는 모양을 줬거나).
   * 그때 `delegatorSubs` 는 비지만, 그 빈 목록은 「없다」가 아니라 **「모른다」**다.
   */
  unavailable: boolean;
};

/**
 * 🔴 **「이 자리에서는 포털에 묻지 않았다」를 글자로 적는 자리.**
 *
 * `{ delegatorSubs: [], unavailable: false }` 를 그 자리에 바로 쓰면 「묻고 보니 없었다」와
 * 「아예 안 물었다」가 똑같이 생긴다. 이름을 붙여 두면 **왜 안 물었는지**를 부르는 쪽 주석이
 * 설명하게 된다.
 *
 * 🔴 `unavailable` 이 **거짓**인 것에 뜻이 있다. 안 물은 것은 장애가 아니므로 「포털을
 * 확인하지 못했습니다」 안내가 뜨면 안 된다 — 뜨면 아무 상관없는 화면마다 경고가 깔린다.
 *
 * 지금 이 상수가 쓰이는 자리는 **포털이 우리를 부르는 통로 둘**이다
 * (`app/api/integration/{approvals,notifications}`). 거기서 또 포털에 물으면 **포털이 우리를
 * 기다리는 동안 우리가 포털을 기다린다** — 포털의 상한이 1.5초인데 우리 상한이 2초라, 물어
 * 봤자 답이 닿기 전에 포털이 그 줄을 버린다. 까닭은 그 두 파일에 적혀 있다.
 */
export const NO_PORTAL_DELEGATIONS: PortalDelegations = { delegatorSubs: [], unavailable: false };

/**
 * 포털이 돌려준 몸통에서 `subs` 만 꺼낸다.
 *
 * @param payload 포털의 답(JSON 을 푼 값). 모양: `{ subs: ["…"], count: N }`.
 * @param subject 물어본 사람의 포털 번호. 🔴 **답에 이 번호가 있어야 한다**(아래).
 * @returns 읽었으면 번호 목록, 🔴 **모르는 모양이면 빈 목록이 아니라 `null`**.
 *
 * ── 🔴 모르는 모양을 「위임 없음」으로 읽지 않는다 ──────────────────────
 * 포털이 통로를 고치다 칸 이름이 바뀐 날 「위임이 하나도 없다」로 **조용히** 읽히면, 대리인
 * 전원이 까닭 없이 막히는데 로그에도 화면에도 아무 흔적이 없다. 그래서 `null`(= 못 읽었다)로
 * 돌려주고 부르는 쪽이 그것을 「못 물었다」로 다룬다.
 *
 * ── 🔴 **답에 부른 사람 자신이 없으면 그것도 「못 읽었다」**다 ────────────
 * 포털의 약속은 「`subs[0]` 은 언제나 부른 사람 자신」이다(설계 C-2 · 포털의
 * `resolveActingApproverSubjects` 가 타입으로 그 꼴을 강제한다). 그 약속이 깨진 답은 **우리가
 * 아는 그 답이 아니다.** 가장 무서운 갈림이 **방향이 뒤집히는 것**인데(「내가 대신할 수 있는
 * 사람들」 ↔ 「나를 대신할 수 있는 사람들」), 그때 그대로 합치면 **남의 결재를 누를 수 있게
 * 된다.** 모양이 낯설면 권한을 늘리지 않는 쪽으로 간다 — 잃는 것은 위임뿐이고, 본인 결재는
 * 멀쩡히 돈다.
 */
export function readPortalDelegationSubs(payload: unknown, subject: string): string[] | null {
  if (typeof payload !== "object" || payload === null) return null;
  const subs = (payload as { subs?: unknown }).subs;
  if (!Array.isArray(subs)) return null;
  const clean = subs.filter((one): one is string => typeof one === "string" && one !== "");
  // 🔴 걸러 낸 **뒤**에 본다 — 번호가 글자가 아닌 답도 우리가 아는 그 답이 아니다.
  if (!clean.includes(subject)) return null;
  return clean;
}

/**
 * 결과에 **「포털에 못 물은 채로 판정했다」**를 얹는다.
 *
 * ── 🔴 왜 결과에 싣나 ───────────────────────────────────────────────────
 * 설계 B-7 의 안내(「지금은 위임이 안 듣습니다」)를 띄우는 것은 **화면의 일**인데, 화면이 그
 * 사실을 알 길이 결과값밖에 없다. 여기서 싣지 않으면 안내를 붙이려는 사람이 결재 쪽 함수를
 * 다시 열어야 하고, 그때 하나를 빠뜨리면 「어떤 화면에서만 안내가 뜬다」가 된다.
 *
 * ── 🔴 `boolean` 이 아니라 `true` 뿐인 까닭 ─────────────────────────────
 * 칸이 `boolean` 이면 「물어봤는데 멀쩡했다」가 `false` 로 **실려** 다니게 되고, 받는 쪽이
 * `portalDelegationUnavailable !== undefined` 같은 식으로 읽는 날 **멀쩡한 결재에도 안내가
 * 뜬다.** 값이 `true` 하나뿐이면 「칸이 있다 = 못 물었다」가 되어 그 길이 막힌다.
 *
 * ── 🔴 성공·실패를 가리지 않는다 ────────────────────────────────────────
 * 막힌 쪽에 필요한 것은 분명하다 — 위임으로 통과했어야 할 사람이 막힌 그 순간이다. 성공한
 * 쪽에도 그대로 싣는 까닭은 **가지를 두지 않기 위해서**다: 「어느 때만 실린다」가 생기면
 * 화면이 그 조건을 한 벌 더 적게 되고, 두 벌이 갈리는 날 안내가 조용히 사라진다. 보여 줄지는
 * 화면이 정한다(값이 있다고 반드시 띄워야 하는 것은 아니다).
 *
 * 🔵 못 물은 적이 없으면 **받은 값을 그대로 돌려준다** — 새 객체를 만들지 않으므로 평소(포털이
 * 멀쩡할 때)에는 아무 비용도 없다.
 */
export function notePortalDelegationOutage<T extends { portalDelegationUnavailable?: true }>(
  result: T,
  portal: PortalDelegations,
): T {
  if (!portal.unavailable) return result;
  return { ...result, portalDelegationUnavailable: true };
}
