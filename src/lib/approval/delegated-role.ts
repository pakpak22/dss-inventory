import type { Role } from "@/db/schema/users";
import { roleAtLeast } from "@/lib/auth/role";
import type { ActingApproverSubs } from "./delegation";

/**
 * ============================================================================
 * 결재권 위임이 **역할까지 넘긴다** — 순수 규칙 (2026-11-17, 설계 B-10·B-11)
 * ============================================================================
 * 사용자 결정: **「재고관리의 결재권 위임은 역할 위임을 포함하는 개념」**이다. `ADMIN` 으로
 * 등록된 사람이 누군가에게 결재권을 맡기면, 그 사람은 **위임 기간 동안 `ADMIN`** 이다.
 * 별도 기능을 만들지 않고 이미 있는 위임 한 줄에 뜻을 더했다.
 *
 * ── 🔴 「`ADMIN` 을 준다」는 「결재권을 준다」가 아니다 ───────────────────
 * 이 집의 승인·반려는 `(결재건, REQUESTED, 결재자 = 내 포털 번호)` 로 판정하고 **역할을 보지
 * 않는다**(설계 D-7 ①). `VIEWER` 여도 결재선에 이름이 있으면 누르고, `ADMIN` 이어도 없으면 못
 * 누른다. 그래서 이 파일은 **결재 판정을 한 글자도 건드리지 않는다** — 여기서 정해지는 것은
 * 「역할이 여는 다른 문들」(재고 직접 조정 · 엑셀 일괄 반영 · 거래 취소 · 부품 삭제 …)이다.
 * 🔴 **역할을 결재 판정에 끼워 넣지 마라.** 끼우는 순간 「결재선에 없는데 누를 수 있는 사람」이
 * 생기고, 그 건은 나중에 「왜 저 사람이 눌렀나」에 답할 자리가 없다.
 *
 * ── 🔴 DB 의 역할 칸을 **쓰지 않는다** (설계 D-7 ④) ─────────────────────
 * 이 집은 역할을 **매 요청마다 DB 에서 다시 읽는다**(`src/lib/auth/session.ts`). 그래서 「**지금**
 * 유효한 위임의 위임자 중 `ADMIN` 이 있나」를 **판정 시점에 계산**하면 된다 — 기간이 끝나면
 * **저절로** 닫히고 야간 작업도 만료 처리도 필요 없다.
 * 🔴 `users.role` 을 바꿔 적는 길로 가지 마라. 그 순간 **여는 조건과 닫는 조건이 다른 곳에**
 * 생기고(여는 것은 위임 줄, 닫는 것은 사람의 손), 화면에서 내릴 수 없는 권한이 남는다.
 *
 * ── 🔴 B-11 — **결재선 설정 변경만은 넘기지 않는다** ────────────────────
 * `ADMIN` 이 여는 문 가운데 **그것 하나만 기간을 넘어 남는다.** 단계를 0개로 비우면 결재가
 * 통째로 꺼지고 부품이 바로 불출되는데, 위임이 끝나도 **그 설정은 그대로다.** 자신을 유일
 * 승인자로 박아 두는 것도 같다. 나머지 문은 기간이 끝나면 더 못 쓰므로(이미 적힌 기록은 상쇄만
 * 가능) 돌려놓을 수 있다. 🔵 그 하나를 가르는 자가 아래 `mayChangeApprovalRoute` 다.
 *
 * ── 🔵 왜 순수 모듈인가 ────────────────────────────────────────────────
 * 표를 읽는 층(`./delegation-queries.ts`)은 `server-only` 를 물고 있어 **시험이 불러올 수
 * 없다.** 그래서 뜻은 여기 두고 저쪽은 「읽어다 넘기는 일」만 한다 — `./delegation-authority.ts`
 * 와 같은 자리, 같은 까닭이다.
 * ============================================================================
 */

/**
 * 🔴 **이 역할의 위임자만 역할을 넘긴다.** `STAFF` 가 맡긴 위임은 결재권만 넘어가고 역할은
 * 그대로다 — 넘길 것이 없기 때문이다(받는 사람이 이미 그 역할 이상일 수도 있다).
 *
 * 🔵 상수로 두는 까닭은 `./delegation-authority.ts` 의 `DELEGATION_MANAGE_ROLE` 과 같다:
 *    글자를 여러 곳에 흩지 않으려는 것이고, 시험이 「무엇이 기준인가」를 이 이름으로 물을 수
 *    있게 하려는 것이다.
 */
export const DELEGATED_ADMIN_SOURCE_ROLE: Role = "ADMIN";

/**
 * 「지금 이 사람이 **대신하는 사람들**」만 추린다 — 판정 목록에서 본인을 뺀 나머지.
 *
 * 🔴 **본인을 빼는 일은 여기 한 번뿐이다.** `actingApproverSubs` 는 **맨 앞에 언제나 본인**을
 * 넣어 돌려준다(그 함수의 타입이 빈 목록을 허락하지 않는 까닭). 그 본인 번호를 그대로 들고
 * 가면 아래 역할 판정이 **자기 역할을 자기에게서 물려받는 꼴**이 되고, 그러면 진짜 `ADMIN` 이
 * 전부 「위임으로 받은 임시 `ADMIN`」으로 둔갑해 **B-11 에 걸려 결재선을 못 고치게 된다.**
 *
 * 🔵 **차례가 아니라 값으로 뺀다.** 「맨 앞이 본인」은 저쪽이 지키는 약속이지만, 그 약속에
 *    기대어 `slice(1)` 로 적으면 차례가 바뀌는 날 **엉뚱한 사람의 역할을 물려받는다** — 오류는
 *    나지 않는다.
 * 🔵 이 함수가 `./delegation.ts`(결재 판정) 가 아니라 여기 있는 까닭: 결재 길목은 본인을 뺄
 *    일이 없다. 본인 차례를 누르는 것이 가장 흔한 일이라, 거기서는 **본인이 들어 있는 것이
 *    옳다.**
 *
 * @param actingSubs `actingApproverSubs` 가 돌려준 목록(본인 + 지금 대신할 수 있는 결재권자들).
 * @param actorSub 「지금 그 사람」의 포털 번호 — 위 목록을 만들 때 쓴 바로 그 값.
 */
export function delegatorSubsOf(actingSubs: ActingApproverSubs, actorSub: string): string[] {
  return actingSubs.filter((sub) => sub !== actorSub);
}

/**
 * 지금 이 요청에서 **쓸 역할**과, 그것이 **위임으로 받은 것인가**.
 *
 * 🔴 두 칸을 **함께** 들고 다닌다. 역할만 들고 다니면 B-11 을 걸 자리가 사라지고(임시인지 알
 * 길이 없다), 깃발만 들고 다니면 역할을 읽는 자리마다 승격을 다시 적어야 한다.
 */
export type DelegatedRoleDecision = {
  /** 🔴 **이번 요청에서 쓰이는 역할.** 승격됐으면 `ADMIN`, 아니면 포털이 준 그대로. */
  role: Role;
  /**
   * 🔴 **위임으로 받은 임시 `ADMIN` 인가.** 진짜 `ADMIN` 은 위임을 받았든 안 받았든 **언제나
   * `false`** 다 — 이 깃발은 「권한이 있나」가 아니라 **「B-11 에 걸리나」**를 가르는 값이다.
   */
  delegatedAdmin: boolean;
};

/**
 * 「지금 이 사람이 임시 `ADMIN` 인가」를 가르는 **유일한 자리**.
 *
 * @param ownRole 포털이 준 진짜 역할(`users.role` 의 지금 값).
 * @param delegatorRoles 지금 **내가 대신하는 사람들**의 역할. 🔴 두 고지(이 집의 위임 ·
 *   승인함에서 맡겨 포털이 써 준 위임)를 **이미 합쳐서** 넘긴 값이어야 한다 — 합치는 자리는
 *   `actingApproverSubs` 하나고(설계 B-12), 여기서 고지를 다시 가르지 않는다.
 *   🔵 역할을 못 찾은 위임자는 **애초에 목록에 없다**(읽는 쪽 주석) — 여기서 「모름」을 다루지
 *   않는 까닭이고, 빈 목록은 「대신하는 사람이 없다」와 같은 뜻으로 읽힌다.
 *
 * ── 🔴 진짜 `ADMIN` 은 **좁아지지 않는다** ─────────────────────────────
 * 역할이 둘이면 **높은 쪽이 이긴다.** 진짜 `ADMIN` 이 누군가의 대리인이기도 할 때 `true` 로
 * 적으면, 그 사람은 **위임을 받았다는 이유만으로** 결재선 설정을 잃는다(B-11). 그래서 먼저
 * 본인 역할을 보고 끝낸다.
 *
 * ── 🔵 승격은 **한 겹**이다 ────────────────────────────────────────────
 * 임시 `ADMIN` 이 또 누군가에게 맡겨도 그 사람은 `ADMIN` 을 얻지 못한다 — 받는 목록
 * (`delegatorSubsFor`)이 이어 붙지 않기 때문이고, 여기서도 되풀이하지 않는다.
 */
export function decideDelegatedRole(ownRole: Role, delegatorRoles: readonly Role[]): DelegatedRoleDecision {
  // 🔴 진짜 ADMIN 은 더 얻을 것도, 잃을 것도 없다(위 머리말).
  if (roleAtLeast(ownRole, DELEGATED_ADMIN_SOURCE_ROLE)) return { role: ownRole, delegatedAdmin: false };
  // 🔵 사다리로 잰다 — 이 저장소가 역할을 가르는 다른 자리와 같은 잣대다(`roleAtLeast`).
  if (!delegatorRoles.some((role) => roleAtLeast(role, DELEGATED_ADMIN_SOURCE_ROLE))) {
    return { role: ownRole, delegatedAdmin: false };
  }
  return { role: DELEGATED_ADMIN_SOURCE_ROLE, delegatedAdmin: true };
}

/**
 * 🔴 **B-11 에 걸린 사람이 보는 글.** 「권한이 없습니다」로 끝내면 임시 `ADMIN` 은 **자기가 왜
 * 그것만 못 하는지** 모른다 — 다른 관리자 화면은 전부 열려 있기 때문이다. 그래서 세 가지를
 * 함께 적는다: **무엇이 막았나**(위임으로 받은 자격) · **왜**(기간이 끝나도 남는다) ·
 * **어떻게 하나**(관리자에게 요청).
 *
 * 🔵 문구에 **기간도 위임자 이름도 싣지 않는다** — 그 값을 실으려면 남의 위임 줄을 읽어야 하고,
 *    거절 문구는 요청을 손으로 만든 사람에게도 그대로 돌아간다(`./delegation-mutations.ts` 의
 *    `DELEGATION_REVOKE_REJECTED_MESSAGE` 와 같은 규약).
 */
export const APPROVAL_ROUTE_DELEGATED_ADMIN_MESSAGE =
  "결재권 위임으로 받은 관리자 자격으로는 승인 절차를 바꿀 수 없습니다. 바꾼 절차는 위임 기간이 끝난 뒤에도 그대로 남기 때문입니다. 절차를 고쳐야 하면 관리자에게 요청하십시오.";

/**
 * 🔴 **승인 절차(결재선)를 고칠 수 있나** — B-11 을 가르는 유일한 자리.
 *
 * 🔴 **화면 분기가 아니다.** 서버 액션(`src/app/actions/approval-routes.ts`)이 이것을 물어
 * 거절한다 — 그 액션은 네트워크 경계 너머에서 불리고, 화면이 단추를 안 그리는 것은 울타리가
 * 아니다(그 파일 머리말과 같은 까닭).
 *
 * @param role 이번 요청에서 쓰이는 역할(승격됐으면 승격된 값).
 * @param delegatedAdmin 위 `decideDelegatedRole` 이 세운 깃발. 🔴 **기본값을 두지 마라** —
 *   빠뜨린 자리에서만 B-11 이 조용히 풀리고, 그 자리에는 아무 표시도 남지 않는다.
 */
export function mayChangeApprovalRoute(role: Role, delegatedAdmin: boolean): boolean {
  return roleAtLeast(role, DELEGATED_ADMIN_SOURCE_ROLE) && !delegatedAdmin;
}
