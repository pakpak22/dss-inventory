/**
 * ============================================================================
 * O/H 단가를 **푸는 곳 한 군데** — 비어 있으면 그 부품의 견적가를 쓴다
 * ============================================================================
 * 🔴 **2026-10-22 오후, 쓰는 분 결정.** 그 전(커밋 `9d8df96`, 같은 날 아침)에는 반대였다 —
 *    「O/H 단가가 비면 견적가를 **회색으로 비쳐 주기만** 한다. 값이 아니라 안내다. 누르면
 *    그때 칸에 들어간다」였고, `[견적가 N원 적용]` 단추가 그 「누르는 몸짓」이었다.
 *    쓰는 분이 그날 오후에 뒤집으셨다:
 *
 *      「비워 두면 견적가가 자동으로 쓰인다. 나중에 견적가가 바뀌면 따라서 바뀐다.
 *       그렇게 되면 [견적가 적용]이라는 단추도 필요 없어질 테니까.」
 *
 *    그래서 단추를 없앴고, **값을 복사해 두지 않는다** — 복사하면 그 순간의 숫자에 묶여
 *    「따라 바뀐다」가 깨진다. 저장은 여전히 빈 값을 `null` 로 두고(행을 지운다), **푸는 일은
 *    읽을 때마다 여기서** 한다.
 *
 * ── 🔴 뜻이 셋이고, 둘을 뭉개면 못 되돌린다 ────────────────────────────
 *   | 저장된 값        | 뜻                      | 나가는 값            |
 *   |------------------|-------------------------|----------------------|
 *   | `null`(행 없음)  | 「견적가를 따른다」     | `parts.quote_price`  |
 *   | `0`              | 🔴 「O/H 때는 무상」    | `0`                   |
 *   | 숫자             | 사람이 정한 O/H 단가    | 그 숫자              |
 *
 *   🔴 `0` 과 빈 값이 다른 뜻인 것은 이 저장소의 **앞선 결정**이고(2026-10-14,
 *   `src/db/schema/oh-templates.ts` 의 `part_overhaul_unit_prices` 머리말), 이번 변경이
 *   그것을 건드리지 않는다. 그래서 아래 함수는 `||` 도 `?? 0` 도 쓰지 않고 **`null` 인지만**
 *   본다 — `stored || quotePrice` 로 적으면 무상(`0`)인 부품이 견적가로 청구되고,
 *   그 견적서를 받은 사람은 무상으로 약속받은 것을 청구당한다.
 *
 * ── 🔴 푸는 자리는 **하나**여야 한다 ───────────────────────────────────
 * 같은 폴백을 두 시스템이 각자 계산하면 언젠가 서로 다른 값을 말한다(이 묶음에서 실제로 겪은
 * 사고다). 두 숫자(`parts.quote_price` · `part_overhaul_unit_prices.unit_price`)를 **재고관리가
 * 다 쥐고 있으므로 여기서 푼다** — A/S 는 이미 풀린 값을 받아, 한 글자도 안 고친다.
 * 화면(`OhTemplateScreen`)도 통로(`toApiPart`)도 이 함수 하나를 부른다.
 *
 * 🔴 **`server-only` 를 붙이지 않는다.** 화면(클라이언트)이 부르고 시험도 부른다.
 * ============================================================================
 */

/**
 * 이 부품을 **오버홀 견적서에 올릴 때의 단가**. 저장된 O/H 단가가 있으면 그 값이고,
 * 없으면(`null` = 「견적가를 따른다」) 그 부품의 일반 견적가다. 둘 다 없으면 `null` —
 * 정할 수 있는 값이 하나도 없다는 뜻이라 받는 쪽이 칸을 비우고 사람이 채운다.
 *
 * @param storedUnitPrice `part_overhaul_unit_prices.unit_price` (행이 없으면 `null`)
 * @param quotePrice      `parts.quote_price` (정하지 않았으면 `null`)
 */
export function resolveOverhaulUnitPrice(
  storedUnitPrice: number | null,
  quotePrice: number | null,
): number | null {
  // 🔴 `stored ?? quotePrice` 와 같은 뜻이지만 일부러 풀어 적는다 — 다음 사람이 `||` 로
  //    「줄여」 쓰면 무상(`0`)이 조용히 견적가로 바뀐다. 오류도 안 나고 시험 이름도 안 바뀐다.
  if (storedUnitPrice !== null) return storedUnitPrice;
  return quotePrice;
}

/**
 * 지금 나가는 값이 **견적가를 따라간 것인가**. 저장된 O/H 단가가 없으면 참이다.
 *
 * 🔵 화면이 「이 숫자는 견적가에서 온 것」이라고 적는 데만 쓴다. 🔴 **통로(API)로는 내보내지
 *    않는다** — 까닭은 `src/lib/api/parts.ts` 의 `ApiPart.overhaulQuotePrice` 머리말에.
 */
export function overhaulUnitPriceFollowsQuote(storedUnitPrice: number | null): boolean {
  return storedUnitPrice === null;
}
