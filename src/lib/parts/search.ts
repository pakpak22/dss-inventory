/**
 * 고르개가 들여다보는 여섯 칸. `PartRow`(재고 현황)도 `OhPartLinkOption`(O/H 고르개 목록)도
 * 이 모양을 품는다 — 고르개가 한 벌이므로 **찾는 칸도 한 벌**이어야 한다.
 */
export type PartQueryFields = {
  no: number;
  name: string;
  name2: string;
  /** 고객사에 나가는 서류에 쓸 품명. 없으면 빈 글자다(`parts.customer_name`). */
  customerName: string;
  drawingNo: string;
  kyosanPartNo: string;
};

/** 친 글자를 낱말로 가른다. 소문자로 맞추는 것도 여기서 한 번만 한다. */
export function tokenizePartQuery(query: string): string[] {
  return query.toLowerCase().split(/\s+/).filter(Boolean);
}

/**
 * 이 부품이 물음말에 맞는가. 낱말은 **전부** 들어 있어야 한다(머리말).
 *
 * @param tokens `tokenizePartQuery` 가 만든 낱말들. **이미 소문자**여야 한다 — 줄마다 다시
 *   소문자로 바꾸면 300줄 × 낱말 수만큼 헛일을 한다.
 */
export function matchesPartQuery(part: PartQueryFields, tokens: readonly string[]): boolean {
  // 🔵 빈 물음말은 아무것도 고르지 않는다(머리말).
  if (tokens.length === 0) return false;
  const hay =
    `${part.no} ${part.name} ${part.name2} ${part.customerName} ${part.drawingNo} ${part.kyosanPartNo}`.toLowerCase();
  return tokens.every((token) => hay.includes(token));
}
