/**
 * 다섯 칸. **키는 `parts` 표의 칸 이름 그대로**라 `PartRow[key]` 로 값을 바로 꺼낼 수 있고,
 * 라벨은 화면에 그대로 나간다(찾을 곳 체크·표 머리글·작은 글씨 라벨이 같은 글자를 쓴다).
 */
export const PART_FIELDS = [
  { key: "customerName", label: "고객사 품명" },
  { key: "name", label: "품명" },
  { key: "name2", label: "품명2" },
  { key: "kyosanPartNo", label: "교산 품번" },
  { key: "drawingNo", label: "도번" },
] as const;

export type PartFieldKey = (typeof PART_FIELDS)[number]["key"];

/** 라벨만 떼어 둔 것. 자기 키를 따로 쓰는 목록(찾을 곳 체크 상자)이 **라벨로** 차례를 맞춘다. */
export const PART_FIELD_LABELS: readonly string[] = PART_FIELDS.map((f) => f.label);

/**
 * 품명을 뺀 넷 — **품명이 이미 줄 머리에 서 있는** 화면이 쓴다(부품 요청 관리의 작은 글씨 목록).
 * 뺀 자리만 빠지고 나머지 차례는 위 표 그대로다.
 */
export const PART_FIELDS_WITHOUT_NAME: ReadonlyArray<{ key: Exclude<PartFieldKey, "name">; label: string }> = PART_FIELDS.filter(
  (f): f is Exclude<(typeof PART_FIELDS)[number], { key: "name" }> => f.key !== "name",
);
